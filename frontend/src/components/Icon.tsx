export type IconName = keyof typeof strokeIcons | keyof typeof fillIcons

type IconProps = Omit<SVGProps<SVGSVGElement>, 'name'> & {
  name: IconName
  size?: number
  strokeWidth?: number
  /** Accessible name; without it the icon is decorative. */
  label?: string
}

export function Icon({ name, size = 20, strokeWidth = 1.8, label, className, ...rest }: IconProps) {
  const a11y = label ? { role: 'img', 'aria-label': label } : { 'aria-hidden': true as const }
  const common = {
    width: size,
    height: size,
    viewBox: '0 0 24 24',
    focusable: false,
    className: cx('shrink-0', className),
    ...a11y,
    ...rest,
  }

  if (name in fillIcons) {
    return (
      <svg fill="currentColor" {...common}>
        {fillIcons[name as keyof typeof fillIcons]}
      </svg>
    )
  }
  return (
    <svg
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      {...common}
    >
      {strokeIcons[name as keyof typeof strokeIcons]}
    </svg>
  )
}
